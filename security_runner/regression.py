"""Regression-test generation for confirmed findings (proposals only: never touches the target).

pytest tests are real and runnable: they assert the *secure* behavior (the rule that found
the issue no longer fires on that file). ``verify_red_green`` proves a generated test fails
against a vulnerable tree and passes against a fixed tree.
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

from . import adapters
from .adapters.base import ScanContext
from .discovery import discover
from .sandbox import safe_run

FRAMEWORKS = ("pytest", "playwright", "schemathesis")


def observations_for(check_id: str, root: str | Path, only_file: str | None = None) -> list[tuple[str, int]]:
    """Run one registered rule against ``root``; returns (file, line) observations."""
    adapters.load_all()
    found = discover(root)
    ctx = ScanContext(Path(found["root"]), found["files"], found["domains"])
    ctx.begin_rule()
    res = adapters.RULES[check_id](ctx)
    if res is None:
        return []
    return sorted((o.file, o.line) for o in res.observations if only_file is None or o.file == only_file)


