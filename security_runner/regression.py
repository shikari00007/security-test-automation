def generate(finding: dict, target: str | Path, outdir: str | Path, framework: str = "pytest",
             accept_candidate: bool = False) -> Path:
    if framework not in FRAMEWORKS:
        raise ValueError(f"unsupported framework {framework!r}; supported: {', '.join(FRAMEWORKS)} "
                         "(JUnit/XCTest/Espresso generators are not implemented yet)")
    st = finding.get("status")
    if st != "confirmed" and not (accept_candidate and st == "candidate" and finding.get("verification")):
        raise ValueError("regression tests are generated for confirmed findings; for a reproduced static candidate pass "
                         "accept_candidate=True / --accept-candidate (run `security-skills audit` verification first)")
    provenance = "CONFIRMED finding" if st == "confirmed" else "CANDIDATE (static match, not a confirmed vulnerability)"
    target = Path(target).resolve()
    out = Path(outdir).resolve()
    if out == target or target in out.parents:
        raise ValueError("regression output must be outside the target tree (proposals are never written into source)")
    out.mkdir(parents=True, exist_ok=True)
    fid = finding["id"]
    ident = re.sub(r"[^0-9a-zA-Z]", "_", fid).lower()
    loc = finding["location"]
    ctx = dict(fid=fid, check_id=finding["check_id"], expected=finding["expected_secure_behavior"],
               root=str(target), ident=ident, path=loc["path"], line=loc["line"],
               title=finding["title"].replace('"', "'"), provenance=provenance)
    if framework == "pytest":
        p, body = out / f"test_{ident}.py", PYTEST_TMPL.format(**ctx)
    elif framework == "playwright":
        p, body = out / f"{ident}.spec.ts", PLAYWRIGHT_TMPL.format(**ctx)
    else:
        p, body = out / f"{ident}.schemathesis.txt", SCHEMATHESIS_TMPL.format(**ctx)
    p.write_text(body, encoding="utf-8")
    return p


def _pytest(test: Path, root: Path) -> int:
    pkg_parent = str(Path(__file__).resolve().parents[1])
    r = safe_run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", str(test)],
                 allowed={os.path.basename(sys.executable)}, allowed_paths={sys.executable},
                 cwd=str(test.parent), timeout=120,
                 extra_env={"SECURITY_TARGET_ROOT": str(root), "PYTHONPATH": pkg_parent})
    return -1 if r.timed_out else (r.exit_code if r.exit_code is not None else -1)


def verify_red_green(test: str | Path, vulnerable: str | Path, fixed: str | Path) -> dict:
    """Run a generated pytest against vulnerable and fixed trees. ok only if red then green."""
    test = Path(test).resolve()
    red, green = _pytest(test, Path(vulnerable).resolve()), _pytest(test, Path(fixed).resolve())
    return {"red_exit": red, "green_exit": green, "ok": red == 1 and green == 0,
            "meaning": "ok = fails on vulnerable tree (exit 1) and passes on fixed tree (exit 0)"}
